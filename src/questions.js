export function makeQuestion(round = 0, grade = '5') {
  const list = banks[grade] || banks[5];
  const item = list[round % list.length];
  const opts = [...item[2]];
  const shift = round % opts.length;
  const shuffled = opts.slice(shift).concat(opts.slice(0, shift));
  return {
    q: item[0],
    a: item[1],
    opts: shuffled,
    topic: item[3],
    id: `${grade}-${round}`,
  };
}

export const questionCount = Object.values(banks).reduce((sum, list) => sum + list.length, 0);
